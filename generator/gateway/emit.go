// Emit writes the runtime coverage table to path as package gateway. The
// runtime package does not import this one — a generator tree has no business
// being linked into the shipped binary — so the Level constants are declared on
// both sides and TestLevelsMatchTheGenerator pins them together.
func Emit(cov *Coverage, entries []Entry, path string) error {
	var b bytes.Buffer

	proVer, classicVer, sdkCommit := "", "", ""
	if cov != nil {
		proVer, classicVer = cov.Sources.Pro.Version, cov.Sources.Classic.Version
		sdkCommit = cov.Sources.SDKCommit
	}

	fmt.Fprintf(&b, `// Copyright 2026, Jamf Software LLC

// Code generated by generator/gateway. DO NOT EDIT.
//
// Which Jamf Pro and Classic operations this CLI can send that the Jamf
// Platform gateway does not publish, derived from jamfplatform-go-sdk's
// api/pro_api.json and api/classic_api_resource_documentation.json via
// specs/gateway/coverage.json. Regenerate with:
//
//	make sync-gateway-coverage-from-sdk JAMFPLATFORM_SDK_PATH=/path/to/jamfplatform-go-sdk
//
// Only the operations this CLI actually sends are listed, so the table is the
// intersection of "the gateway omits it" and "a command exists for it" — not a
// mirror of the gateway's spec.

package gateway

// Provenance of the manifest this table was derived from. Empty when the tree
// held no manifest at generate time, which is the "unknown" case: Lookup then
// finds nothing and no command is refused.
const (
	ProAPIVersion     = %s
	ClassicAPIVersion = %s
	SDKCommit         = %s
)

// unserved is sorted by path then method. Paths are gateway-form with every
// path parameter rendered as {}, matched segment-wise by Lookup. Every entry is
// refused before a request is sent on a gateway profile; Basis selects the
// wording, not the behaviour.
var unserved = []Finding{
`, strconv.Quote(proVer), strconv.Quote(classicVer), strconv.Quote(sdkCommit))

	for _, e := range entries {
		fmt.Fprintf(&b, "\t{Method: %s, Path: %s, Level: %s, Basis: %s, Detail: %s},\n",
			strconv.Quote(e.Method), strconv.Quote(e.Path),
			levelConst(e.Level), basisConst(e.Basis), strconv.Quote(e.Detail))
	}
	b.WriteString("}\n")

	writeScopeRules(&b, cov)

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("formatting %s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, src, 0o644)
}

// writeScopeRules emits the gateway scope each published operation requires, as
// a flat table the runtime scans on a 403.
//
// The whole manifest is emitted rather than the intersection with the operations
// this CLI's generated commands send, unlike unserved above. The consumer is a
// concrete failing request, and the hand-written commands assemble paths the
// generator never enumerates — `pro overview` alone sends ~41 — so narrowing to
// generated ops would leave exactly the fan-out commands without a hint.
//
// Sorted by path then method so a re-derivation from an unchanged manifest is a
// no-op diff.
func writeScopeRules(b *bytes.Buffer, cov *Coverage) {
	b.WriteString(`
// scopeRules is the gateway scope each operation requires, from the published
// specs' x-required-privileges. Paths are gateway-form with every path
// parameter rendered as {}, matched segment-wise by Scopes.
//
// These are Jamf Account capability permissions (categories:read), not Jamf Pro
// API-role privilege names (Read Categories). The two are independent sets — the
// GA consolidation mapped several privileges onto one capability — so this table
// is only ever the right answer for a request going through the gateway.
var scopeRules = []scopeRule{
`)
	if cov == nil {
		b.WriteString("}\n")
		return
	}
	paths := make([]string, 0, len(cov.Scopes))
	for p := range cov.Scopes {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		byMethod := cov.Scopes[p]
		methods := make([]string, 0, len(byMethod))
		for m := range byMethod {
			methods = append(methods, m)
		}
		sort.Strings(methods)
		for _, m := range methods {
			scopes := byMethod[m]
			if len(scopes) == 0 {
				continue
			}
			quoted := make([]string, 0, len(scopes))
			for _, s := range scopes {
				quoted = append(quoted, strconv.Quote(s))
			}
			fmt.Fprintf(b, "\t{Method: %s, Path: %s, Scopes: []string{%s}},\n",
				strconv.Quote(m), strconv.Quote(p), strings.Join(quoted, ", "))
		}
	}
	b.WriteString("}\n")
}

func levelConst(l Level) string {
	if l == Unserved {
		return "Unserved"
	}
	return "Served"
}

func basisConst(b Basis) string {
	if b == BasisProbe {
		return "BasisProbe"
	}
	return "BasisUnpublished"
}
