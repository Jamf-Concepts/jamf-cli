package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// writeProvenanceFile emits provenance.go to outputDir under packageName,
// declaring a stable list of every spec file consumed during generation
// alongside its SHA256. The file is regenerated on every `make generate`
// run; because hashes only change when spec contents change, the output
// is deterministic relative to the input specs (no timestamp embedded).
//
// The version subcommand reads Sources via -v so users can answer
// "which Jamf Pro / Platform spec version is this CLI generated against?"
// without spelunking git history.
func writeProvenanceFile(outputDir, packageName string, specs []string) error {
	type entry struct{ File, SHA256 string }
	sources := make([]entry, 0, len(specs))
	seen := make(map[string]bool, len(specs))
	for _, p := range specs {
		data, err := os.ReadFile(p)
		if err != nil {
			return fmt.Errorf("reading spec %s: %w", p, err)
		}
		sum := sha256.Sum256(data)
		rel := relRepoPath(p)
		if seen[rel] {
			continue
		}
		seen[rel] = true
		sources = append(sources, entry{rel, hex.EncodeToString(sum[:])})
	}
	sort.Slice(sources, func(i, j int) bool { return sources[i].File < sources[j].File })

	var b strings.Builder
	b.WriteString("// Copyright 2026, Jamf Software LLC\n")
	b.WriteString("// Code generated by jamf-cli generator. DO NOT EDIT.\n\n")
	b.WriteString("package " + packageName + "\n\n")
	b.WriteString("// SpecSource is one spec file consumed by code generation.\n")
	b.WriteString("type SpecSource struct {\n")
	b.WriteString("\tFile   string\n")
	b.WriteString("\tSHA256 string\n")
	b.WriteString("}\n\n")
	b.WriteString("// Sources lists every spec file consumed when this package was generated.\n")
	b.WriteString("// Order: stable, by File. Use `jamf-cli version -v` to print.\n")
	b.WriteString("var Sources = []SpecSource{\n")
	for _, s := range sources {
		fmt.Fprintf(&b, "\t{File: %q, SHA256: %q},\n", s.File, s.SHA256)
	}
	b.WriteString("}\n")

	out := filepath.Join(outputDir, "provenance.go")
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// relRepoPath converts an absolute or relative spec path into a stable
// repo-relative path with forward slashes, so provenance.go is identical
// regardless of the contributor's working directory or OS.
func relRepoPath(p string) string {
	abs, err := filepath.Abs(p)
	if err != nil {
		return p
	}
	wd, err := os.Getwd()
	if err != nil {
		return p
	}
	rel, err := filepath.Rel(wd, abs)
	if err != nil {
		return p
	}
	return filepath.ToSlash(rel)
}
